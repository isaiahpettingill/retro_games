static const uint8_t *const tunes[]={bear,ducks,soldier};
static const uint8_t tempos[]={13,8,15};
static uint8_t note_wait,note,tune;
void audio_init(void){
    NR52_REG=0x80;NR50_REG=0x55;NR51_REG=0xff;
}
void sound(uint8_t id){
    static const uint16_t freq[]={0,1450,1740,1070,520,1800,1940};
    uint16_t f=freq[id];if(muted)return;
    if(id==3 || id==4){
        NR41_REG=49;NR42_REG=(id==3?0x72:0x42);NR43_REG=(id==3?0x45:0x31);NR44_REG=0xc0;
    }else{
        NR10_REG=(id==1?0x13:(id==2?0x12:0));
        NR11_REG=0x80|43;NR12_REG=0x82;NR13_REG=(uint8_t)f;NR14_REG=0xc0|(f>>8);
    }
}
void music_tick(void){
    if(muted || game_mode==PAUSE || game_mode==GUIDE || game_mode==CONFIRM)return;
    if(note_wait){--note_wait;return;}
    uint8_t event=tunes[tune][note++];
    if(!event){
        tune=(tune+1u)%3u;note=0;note_wait=22;return;
    }
    uint8_t unit=tempos[tune];
    if(hard_mode && game_mode==PLAY)unit=(unit*(32u-hard_tier))>>5;
    note_wait=(event>>4)*unit-1u;
    uint16_t f=notes[event&15u];
    NR21_REG=0x80u|(64u-(note_wait>30u?30u:note_wait));
    NR22_REG=0x43;NR23_REG=(uint8_t)f;NR24_REG=0xc0|(f>>8);
}
